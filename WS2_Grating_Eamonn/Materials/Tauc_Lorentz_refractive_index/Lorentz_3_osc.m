function [n,k]=Lorentz_3_osc(E,epsinf,A1,C1,E01,A2,C2,E02,A3,C3,E03)

eps1=(A1*(E01^2-E.^2))./((E01^2-E.^2).^2+(C1.*E).^2)+...
     (A2*(E02^2-E.^2))./((E02^2-E.^2).^2+(C2.*E).^2)+...
     (A3*(E03^2-E.^2))./((E03^2-E.^2).^2+(C3.*E).^2)+epsinf;
eps2=(A1*E01*C1)./((E01^2-E.^2).^2+(C1.*E).^2)+...
     (A2*E02*C2)./((E02^2-E.^2).^2+(C2.*E).^2)+...
     (A3*E03*C3)./((E03^2-E.^2).^2+(C3.*E).^2);
 
n=sqrt(0.5*(sqrt(eps1.^2+eps2.^2)+eps1));
k=sqrt(0.5*(sqrt(eps1.^2+eps2.^2)-eps1));
                                                                                                                                         
end